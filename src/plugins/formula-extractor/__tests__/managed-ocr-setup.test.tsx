import { act, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { beforeEach, expect, it, vi } from 'vitest';
const runtime = vi.hoisted(() => ({ status: vi.fn(), install: vi.fn(), cancel: vi.fn(), setting: vi.fn(), getSetting: vi.fn() }));
vi.mock('@/hooks/use-i18n', () => ({ useI18n: () => ({ locale: 'zh-CN' }) }));
vi.mock('@/lib/formula-ocr-managed', () => ({ getManagedFormulaOcrStatus: runtime.status, installManagedFormulaOcr: runtime.install, cancelManagedFormulaOcr: runtime.cancel }));
vi.mock('@/lib/plugins/runtime', () => ({ getPluginSetting: runtime.getSetting, setPluginSetting: runtime.setting }));
import { ManagedOcrSetup } from '../managed-ocr-setup';
beforeEach(() => { vi.clearAllMocks(); runtime.status.mockResolvedValue({ status: 'missing', phase: '', downloadedBytes: 0, totalBytes: 277000000 }); runtime.install.mockResolvedValue(undefined); runtime.setting.mockResolvedValue(undefined); runtime.getSetting.mockImplementation(() => undefined); runtime.cancel.mockResolvedValue(true); });
it('shows the current verified runtime download size instead of an old hardcoded package size',async()=>{
  runtime.status.mockResolvedValue({status:'missing',phase:'',downloadedBytes:0,totalBytes:178433415});render(<ManagedOcrSetup onReady={vi.fn()}/>);
  expect(await screen.findByText(/171 MiB/)).toBeTruthy();expect(screen.queryByText(/266 MiB/)).toBeNull();
});
it('sets up a missing backend and activates it without a command path field', async () => {
  runtime.status.mockResolvedValueOnce({ status: 'missing', downloadedBytes: 0, totalBytes: 277000000 }).mockResolvedValue({ status: 'ready', downloadedBytes: 277000000, totalBytes: 277000000 });
  const ready = vi.fn(); render(<ManagedOcrSetup onReady={ready} />);
  fireEvent.click(await screen.findByRole('button', { name: '启用本地图片公式识别' }));
  await waitFor(() => expect(ready).toHaveBeenCalledTimes(1));
  expect(runtime.install).toHaveBeenCalledTimes(1);
  expect(runtime.setting).toHaveBeenCalledWith('formula-extractor', 'ocrCommand', 'managed');
  expect(screen.queryByRole('textbox')).toBeNull();
});
it('does not activate when native setup returns without a ready health state', async () => {
  const ready = vi.fn(); render(<ManagedOcrSetup onReady={ready} />);
  fireEvent.click(await screen.findByRole('button', { name: '启用本地图片公式识别' }));
  expect(await screen.findByRole('alert')).toBeTruthy();
  expect(ready).not.toHaveBeenCalled(); expect(runtime.setting).not.toHaveBeenCalled();
});
it('keeps setup failures retryable and does not activate an unavailable engine', async () => {
  runtime.install.mockRejectedValue(new Error('download failed'));
  const ready = vi.fn(); render(<ManagedOcrSetup onReady={ready} />);
  fireEvent.click(await screen.findByRole('button', { name: '启用本地图片公式识别' }));
  expect(await screen.findByRole('alert')).toBeTruthy();
  expect(ready).not.toHaveBeenCalled(); expect(runtime.setting).not.toHaveBeenCalled();
  expect(screen.getByRole('button', { name: '启用本地图片公式识别' })).toBeTruthy();
});
it('does not persist managed mode when the setup is closed before installation finishes', async () => {
  let complete!: () => void;
  runtime.install.mockImplementation(() => new Promise<void>(resolve => { complete = resolve; }));
  const ready = vi.fn(); const view = render(<ManagedOcrSetup onReady={ready} />);
  fireEvent.click(await screen.findByRole('button', { name: '启用本地图片公式识别' }));
  await waitFor(() => expect(runtime.install).toHaveBeenCalledTimes(1));
  view.unmount(); runtime.status.mockResolvedValue({ status: 'ready', downloadedBytes: 100, totalBytes: 100 });
  await act(async () => complete());
  expect(runtime.setting).not.toHaveBeenCalled(); expect(ready).not.toHaveBeenCalled();
});
it('preserves an advanced custom command chosen while installation was in progress', async () => {
  let complete!: () => void; let configured: string | undefined;
  runtime.getSetting.mockImplementation(() => configured);
  runtime.setting.mockImplementation(async (_plugin: string, _key: string, value: string) => { configured = value; });
  runtime.install.mockImplementation(() => new Promise<void>(resolve => { complete = resolve; }));
  const ready = vi.fn(); render(<ManagedOcrSetup onReady={ready} />);
  fireEvent.click(await screen.findByRole('button', { name: '启用本地图片公式识别' }));
  await waitFor(() => expect(runtime.install).toHaveBeenCalledTimes(1));
  configured = 'custom-safe-command'; runtime.status.mockResolvedValue({ status: 'ready', downloadedBytes: 100, totalBytes: 100 });
  await act(async () => complete());
  expect(configured).toBe('custom-safe-command'); expect(runtime.setting).not.toHaveBeenCalled(); expect(ready).not.toHaveBeenCalled();
});
it('does not activate from late ready after the user cancels installation', async () => {
  let complete!: () => void;
  runtime.install.mockImplementation(() => new Promise<void>(resolve => { complete = resolve; }));
  runtime.status.mockResolvedValueOnce({ status: 'missing', downloadedBytes: 0, totalBytes: 100 }).mockResolvedValue({ status: 'installing', requestId: 'synthetic-id', downloadedBytes: 20, totalBytes: 100 });
  const ready = vi.fn(); render(<ManagedOcrSetup onReady={ready} />);
  fireEvent.click(await screen.findByRole('button', { name: '启用本地图片公式识别' }));
  const cancel = await screen.findByRole('button', { name: '取消下载' }); await waitFor(() => expect(cancel.hasAttribute('disabled')).toBe(false));
  const installId = runtime.install.mock.calls[0]?.[0];
  expect(installId).toEqual(expect.any(String));
  expect(installId).not.toBe('synthetic-id');
  fireEvent.click(cancel); await waitFor(() => expect(runtime.cancel).toHaveBeenCalledWith(installId));
  runtime.status.mockResolvedValue({ status: 'ready', downloadedBytes: 100, totalBytes: 100 }); await act(async () => complete());
  expect(runtime.setting).not.toHaveBeenCalled(); expect(ready).not.toHaveBeenCalled();
});
it('cancels a retried installation using its new ID before native status refreshes', async () => {
  let complete!: () => void;
  runtime.status.mockResolvedValue({ status: 'cancelled', requestId: 'previous-cancelled-id', downloadedBytes: 0, totalBytes: 100 });
  runtime.install.mockImplementation(() => new Promise<void>(resolve => { complete = resolve; }));
  const ready = vi.fn(); render(<ManagedOcrSetup onReady={ready} />);
  fireEvent.click(await screen.findByRole('button', { name: '启用本地图片公式识别' }));
  const installId = runtime.install.mock.calls[0]?.[0];
  expect(installId).toMatch(/^[a-f\d-]{36}$/i);
  expect(installId).not.toBe('previous-cancelled-id');
  fireEvent.click(await screen.findByRole('button', { name: '取消下载' }));
  await waitFor(() => expect(runtime.cancel).toHaveBeenCalledWith(installId));
  runtime.status.mockResolvedValue({ status: 'ready', downloadedBytes: 100, totalBytes: 100 });
  await act(async () => complete());
  expect(runtime.setting).not.toHaveBeenCalled(); expect(ready).not.toHaveBeenCalled();
});
it('keeps the active installation pending when native cancellation is rejected', async () => {
  let complete!: () => void;
  runtime.status.mockResolvedValue({ status: 'cancelled', requestId: 'previous-cancelled-id', downloadedBytes: 0, totalBytes: 100 });
  runtime.install.mockImplementation(() => new Promise<void>(resolve => { complete = resolve; }));
  runtime.cancel.mockResolvedValue(false);
  const ready = vi.fn(); render(<ManagedOcrSetup onReady={ready} />);
  fireEvent.click(await screen.findByRole('button', { name: '启用本地图片公式识别' }));
  fireEvent.click(await screen.findByRole('button', { name: '取消下载' }));
  expect((await screen.findByRole('alert')).textContent).toContain('取消未成功，安装仍在执行');
  expect(screen.getByRole('progressbar')).toBeTruthy();
  expect(screen.queryByRole('button', { name: '启用本地图片公式识别' })).toBeNull();
  expect(runtime.setting).not.toHaveBeenCalled(); expect(ready).not.toHaveBeenCalled();
  runtime.status.mockResolvedValue({ status: 'ready', downloadedBytes: 100, totalBytes: 100 });
  await act(async () => complete());
  expect(ready).toHaveBeenCalledTimes(1);
  expect(runtime.setting).toHaveBeenCalledWith('formula-extractor', 'ocrCommand', 'managed');
  expect(screen.queryByRole('alert')).toBeNull();
});
it('uses a distinct task ID for each retry instead of the previous status ID', async () => {
  runtime.status.mockResolvedValue({ status: 'cancelled', requestId: 'previous-cancelled-id', downloadedBytes: 0, totalBytes: 100 });
  runtime.install.mockRejectedValue(new Error('cancelled'));
  render(<ManagedOcrSetup onReady={vi.fn()} />);
  fireEvent.click(await screen.findByRole('button', { name: '启用本地图片公式识别' }));
  await screen.findByRole('alert');
  fireEvent.click(screen.getByRole('button', { name: '启用本地图片公式识别' }));
  await waitFor(() => expect(runtime.install).toHaveBeenCalledTimes(2));
  const first = runtime.install.mock.calls[0]?.[0], second = runtime.install.mock.calls[1]?.[0];
  expect(first).toEqual(expect.any(String)); expect(second).toEqual(expect.any(String));
  expect(first).not.toBe(second);
});
it('waits for the cancellation acknowledgement when installation terminates first', async () => {
  let stopInstall!: (error: Error) => void, acknowledge!: (accepted: boolean) => void;
  runtime.status.mockResolvedValue({ status: 'cancelled', requestId: 'previous-cancelled-id', downloadedBytes: 0, totalBytes: 100 });
  runtime.install.mockImplementation(() => new Promise<void>((_resolve, reject) => { stopInstall = reject; }));
  runtime.cancel.mockImplementation(() => new Promise<boolean>(resolve => { acknowledge = resolve; }));
  const ready = vi.fn(); render(<ManagedOcrSetup onReady={ready} />);
  fireEvent.click(await screen.findByRole('button', { name: '启用本地图片公式识别' }));
  fireEvent.click(await screen.findByRole('button', { name: '取消下载' }));
  await act(async () => stopInstall(new Error('OCR_CANCELLED')));
  expect(screen.getByRole('progressbar')).toBeTruthy();
  expect(screen.queryByRole('alert')).toBeNull();
  await act(async () => acknowledge(true));
  expect(screen.getByRole('button', { name: '启用本地图片公式识别' })).toBeTruthy();
  expect(screen.queryByRole('alert')).toBeNull();
  expect(runtime.setting).not.toHaveBeenCalled(); expect(ready).not.toHaveBeenCalled();
});
it('starts only one installation for rapid repeated clicks', async () => {
  runtime.install.mockImplementation(() => new Promise(() => {}));
  render(<ManagedOcrSetup onReady={vi.fn()} />);
  const button = await screen.findByRole('button', { name: '启用本地图片公式识别' });
  act(() => { button.click(); button.click(); });
  expect(runtime.install).toHaveBeenCalledTimes(1);
});
